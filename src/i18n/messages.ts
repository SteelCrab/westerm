/**
 * The saved choice if valid, else the first browser language we support,
 * else English. "zh-TW" and "zh-HK" also map to zh (Simplified for now).
 */
export function detectLocale(saved: string | null, languages: readonly string[]): Locale {
  if (saved && (LOCALES as readonly string[]).includes(saved)) return saved as Locale;
  for (const language of languages) {
    const prefix = language.toLowerCase().split(/[-_]/)[0];
    if ((LOCALES as readonly string[]).includes(prefix)) return prefix as Locale;
  }
  return "en";
}
